def drainage_outputs() -> tuple[list[Path], list[Path], dict]:
    network_summary = pd.read_csv(
        require(ROOT / "data" / "recovered_candidate" / "N1-N5_network_summary.csv")
    )
    robustness = pd.read_csv(require(ROOT / "results" / "N5_robustness_summary.csv"))
    swmm = pd.read_csv(
        require(ROOT / "data" / "swmm" / "extracted" / "swmm_comparison_summary.csv")
    ).iloc[0]

    figures: list[Path] = []
    tables: list[Path] = []

    x = robustness["pct"] * 100
    fig, axes = plt.subplots(1, 2, figsize=(7.16, 2.55))
    axes[0].errorbar(
        x,
        robustness["mean_spearman"],
        yerr=[
            robustness["mean_spearman"] - robustness["p05_spearman"],
            robustness["p95_spearman"] - robustness["mean_spearman"],
        ],
        marker="o",
        capsize=3,
        color=BLUE,
    )
    axes[0].set(xlabel="Susceptibility perturbation (%)", ylabel="Spearman rank correlation", ylim=(0, 1.02))
    axes[0].set_xticks(x)
    axes[0].grid(axis="y")
    axes[1].plot(x, robustness["mean_top_20pct_jaccard"], marker="s", color=AMBER)
    axes[1].set(xlabel="Susceptibility perturbation (%)", ylabel="Top-20% Jaccard", ylim=(0, 1.02))
    axes[1].set_xticks(x)
    axes[1].grid(axis="y")
    figures += save_figure(fig, "fig_drainage_robustness")

    metric_labels = ["Depth\nSpearman", "Flooding\nSpearman", "Depth\nJaccard", "Flooding\nJaccard"]
    metric_values = [
        swmm["mean_depth_spearman"],
        swmm["mean_flooding_spearman"],
        swmm["mean_depth_top20pct_jaccard"],
        swmm["mean_flooding_top20pct_jaccard"],
    ]
    fig, ax = plt.subplots(figsize=(3.5, 2.55))
    bars = ax.bar(metric_labels, metric_values, color=[BLUE, BLUE, AMBER, AMBER], width=0.68)
    ax.axhline(0, color=NAVY, linewidth=0.7)
    ax.set(ylabel="Agreement metric", ylim=(-0.6, 0.25))
    ax.grid(axis="y")
    ax.set_axisbelow(True)
    for bar, value in zip(bars, metric_values):
        offset = 0.025 if value >= 0 else -0.04
        va = "bottom" if value >= 0 else "top"
        ax.text(bar.get_x() + bar.get_width() / 2, value + offset, f"{value:.3f}", ha="center", va=va, fontsize=7)
    figures += save_figure(fig, "fig_drainage_swmm_alignment")

    network_rows = []
    for row in network_summary.itertuples(index=False):
        network_rows.append(
            [
                str(row.Network).split("_", 1)[0],
                row.Nodes,
                row.Edges,
                row.Sources,
                f"{row.Mean_S:.3f}",
                row.Purpose,
            ]
        )
    tables.append(
        write_table(
            "table_drainage_networks.tex",
            caption="Synthetic drainage-network evaluation set.",
            label="tab:drainage-networks",
            headers=["Network", "Nodes", "Edges", "Sources", "Mean $S$", "Primary purpose"],
            rows=network_rows,
            column_spec=r"lrrrrp{7.0cm}",
            wide=True,
        )
    )

    validation_rows = [
        ["Mean depth", f"{swmm['mean_depth_spearman']:.3f}", f"{swmm['mean_depth_top20pct_jaccard']:.3f}", f"{100 * swmm['mean_depth_outside_scope_share']:.1f}%"],
        ["Flooding", f"{swmm['mean_flooding_spearman']:.3f}", f"{swmm['mean_flooding_top20pct_jaccard']:.3f}", f"{100 * swmm['mean_flooding_outside_scope_share']:.1f}%"],
    ]
    tables.append(
        write_table(
            "table_drainage_swmm.tex",
            caption="GBBRPM and SWMM ranking comparison across 12 blockage scenarios.",
            label="tab:drainage-swmm",
            headers=["Hydraulic outcome", "Mean Spearman", "Top-20\\% Jaccard", "Outside-scope share"],
            rows=validation_rows,
            column_spec="lrrr",
            wide=True,
            note="Negative rank correlations and low priority-set overlap are reported without reinterpreting the modeled risk index as a hydraulic predictor.",
        )
    )

    stats = {
        "synthetic_networks": int(len(network_summary)),
        "swmm_scenarios": int(swmm["scenarios"]),
    }
    return figures, tables, stats


